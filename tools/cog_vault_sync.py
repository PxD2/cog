#!/usr/bin/env python3
"""COG vault sync — mirrors the COG library's index from GitHub (PxD2/cog, the host) into the Obsidian vault.

The vault never holds library text. It holds notes that point at the host: live numbers, one note per library
section listing its documents with links to Alexandria, loc.gov and the raw pack on GitHub. Re-run any time;
it only rewrites the generated notes (everything under "COG Library/Live" and "COG Library/Sections").

    python cog_vault_sync.py                                  # default vault: Desktop\\CLAUDE OBSIDIAN\\CLAUDE
    python cog_vault_sync.py --vault "D:\\path\\to\\vault"
    python cog_vault_sync.py --selftest

Reads the public repo over raw.githubusercontent.com; no sign-in needed. Standard library only.
"""
from __future__ import annotations

import argparse, json, re, sys, tempfile, urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO, BRANCH = "PxD2/cog", "main"
RAW = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}/"
GH = f"https://github.com/{REPO}/blob/{BRANCH}/"
SITE = "https://pxd2.github.io/cog/"
APP = SITE + "alexandria/"
DEFAULT_VAULT = Path.home() / "Desktop" / "CLAUDE OBSIDIAN" / "CLAUDE"
FOLDER = Path("PXD2 Studio") / "COG Library"
FMT = {"video": "Video", "audio": "Audio", "image": "Photo", "map": "Map", "manuscript": "Manuscript", "newspaper": "Newspaper",
       "book": "Book", "text": "Text"}
TRUST = "The Library of Congress is a taxpayer trust: held in trust for the people who paid for it, not a government organization or entity."


def fetch(path: str, base: str = RAW):
    try:
        with urllib.request.urlopen(urllib.request.Request(base + path + f"?t={int(datetime.now().timestamp())}",
                                                           headers={"User-Agent": "PXD2-COG-vault-sync"}), timeout=60) as r:
            return json.loads(r.read())
    except Exception:
        return None


def md_escape(t) -> str:
    return re.sub(r"([|\[\]])", r"\\\1", str(t or "")).replace("\n", " ")


def safe_name(t: str) -> str:
    return re.sub(r'[\\/:*?"<>|#^]', "-", t).strip() or "Section"


def year_txt(y) -> str:
    return "" if y in (None, "") else (f"{-y} BC" if isinstance(y, int) and y < 0 else str(y))


def build(get=fetch, now: str | None = None) -> dict[str, str]:
    """Returns {relative path inside FOLDER: markdown}."""
    now = now or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    cat = get("books/catalog.json") or {"books": [], "sections": [], "totals": {}}
    state = get("loc/state.json") or {}
    t = cat.get("totals") or {}
    out: dict[str, str] = {}
    secs = cat.get("sections") or []

    # ---- one note per section
    sec_links = []
    for s in secs:
        name = "COG Section — " + safe_name(s["title"])
        sec_links.append((s, name))
        entries = []
        for f in s.get("index") or []:
            ix = get(f) or {}
            entries.extend(ix.get("e") or [])
        latest = {}
        for e in entries:
            latest[e["id"]] = e
        rows = sorted(latest.values(), key=lambda e: (e.get("y") if isinstance(e.get("y"), int) else 99999, e.get("t") or ""))
        base = s.get("base") or RAW
        lines, fmts = [], {}
        for e in rows:
            if e.get("k") == "article":
                slug = e["id"].split(":", 1)[1]
                lines.append(f"| [{md_escape(e.get('t'))}]({APP}#/a/{slug}) | {year_txt(e.get('y'))} | {md_escape(e.get('s'))} | "
                             f"{md_escape(e.get('sum'))[:140]} | [pack]({(GH if not s.get('base') else base)}{s['files'][e['f'] - 1]}) |")
            else:
                fm = FMT.get(e.get("fm") or "text", e.get("fm") or "")
                fmts[fm] = fmts.get(fm, 0) + 1
                lines.append(f"| [{md_escape(e.get('t'))}]({APP}#/src/{s['id']}/{e['f']}/{e['i']}) | {md_escape(e.get('d') or year_txt(e.get('y')))} | "
                             f"{fm}{' ▶' if e.get('mv') else ''} | {md_escape(e.get('ar') or 'loc.gov')} | {e.get('n', '')} | "
                             f"[pack]({(GH if not s.get('base') else base)}{s['files'][e['f'] - 1]}) |")
        is_art = any(e.get("k") == "article" for e in rows)
        head = ("| Article | Year | Subject | Summary | Data |\n|---|---|---|---|---|" if is_art else
                "| Item | Date | Format | Archive | Sentences | Data |\n|---|---|---|---|---|---|")
        store = "core (PxD2/cog)" if s.get("store") == "core" else s.get("store")
        out[f"Sections/{name}.md"] = f"""---
type: cog-section
section: {s['id']}
title: "{s['title']}"
store: "{s.get('store', 'core')}"
documents: {s.get('docs', 0)}
sentences: {s.get('sentences', 0)}
synced: "{now}"
tags: [cog, cog-section, generated]
---
# {s['title']}

## For future Claude
Generated by `cog_vault_sync.py` from the host (GitHub {REPO}). Do not hand-edit: the next sync rewrites it.
Lists what this library section holds; the text itself lives only on GitHub as COG addresses. Films, recordings,
photographs and maps are never copied: their catalogue text and captions are COG, the media streams from the archive. Open a row in
Alexandria to read it, or the pack link to see the raw data. Hub: [[COG Library]].

**Stored in:** {store} · **Documents:** {s.get('docs', 0):,} · **Sentences:** {s.get('sentences', 0):,}
**Finder index:** {", ".join(f"[{Path(f).name}]({GH}{f})" for f in s.get('index') or []) or "none"}
**Document packs:** {", ".join(f"[{Path(f).name}]({(GH if not s.get('base') else base)}{f})" for f in s.get('files') or [])}
**Formats:** {", ".join(f"{k} {v}" for k, v in sorted(fmts.items())) or "—"} (▶ = plays: film or recording, streamed from the archive)
**Read it:** [{s['title']} in Alexandria]({APP}#/{'explore' if s['id'] == 'encyclopedia' else 'section/' + s['id']})

{head}
{chr(10).join(lines) if lines else "| (nothing yet) |"}
"""

    # ---- live numbers
    packs = [b for b in cat.get("books", []) if b.get("kind") == "meanings"]
    pack_rows = "\n".join(
        f"| [{Path(b['file']).name}]({GH}{b['file']}) | {b.get('room')} | "
        + (f"{b.get('from')}–{b.get('to')}" if b.get("from") is not None else "hand-made (ids < 1000)")
        + f" | {len(b.get('cont') or [])} |" for b in packs)
    src_rows = "\n".join(
        f"| {md_escape(k[2:].replace(' |books', '') if k.startswith('q:') else k)} | {'search' if k.startswith('q:') else 'collection'} | "
        f"{'complete' if v.get('done') else str(v.get('pages', 0)) + ' page(s) in'} | {v.get('updated', '')[:10]} |"
        for k, v in (state.get("sources") or {}).items()) or "| (none yet) | | | |"
    out["Live/COG Library — Live.md"] = f"""---
type: cog-live
synced: "{now}"
next_meaning: {cat.get('next_meaning', state.get('next_meaning', 1000))}
meanings: {t.get('meanings', 0)}
variants: {t.get('variants', 0)}
documents: {t.get('docs', 0)}
sentences: {t.get('sentences', 0)}
tags: [cog, generated]
---
# COG Library — Live

## For future Claude
Generated by `cog_vault_sync.py` from the host's `books/catalog.json` and `loc/state.json` at {now}.
Do not hand-edit. Use it to answer "what's in the library" without opening GitHub. Hub: [[COG Library]].

| Next free meaning-id | Meanings | Exact sentences | Documents | Sentences read |
|---|---|---|---|---|
| **{cat.get('next_meaning', state.get('next_meaning', 1000))}** | {t.get('meanings', 0):,} | {t.get('variants', 0):,} | {t.get('docs', 0):,} | {t.get('sentences', 0):,} |

## Sections
| Section | Stored in | Documents | Sentences |
|---|---|---|---|
{chr(10).join(f"| [[{n}]] | {'core' if s.get('store') == 'core' else s.get('store')} | {s.get('docs', 0):,} | {s.get('sentences', 0):,} |" for s, n in sec_links) or "| (none yet) | | | |"}

## Where each loc.gov source left off
| Source | Kind | Progress | Last run |
|---|---|---|---|
{src_rows}

## Meaning packs (shared dictionary)
| Pack | Room | New meaning-ids | Continued meanings |
|---|---|---|---|
{pack_rows}

Host: [{REPO}](https://github.com/{REPO}) · Site: [{SITE}]({SITE}) · App: [Alexandria]({APP}) · {TRUST}
"""
    return out


def write(vault: Path, files: dict[str, str]) -> list[str]:
    root = vault / FOLDER
    done = []
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
            done.append(rel)
    # sections that no longer exist upstream are moved aside, never deleted
    keep = {Path(r).name for r in files if r.startswith("Sections/")}
    sec_dir = root / "Sections"
    if sec_dir.exists():
        for p in sec_dir.glob("*.md"):
            if p.name not in keep:
                arch = root / "_archive"
                arch.mkdir(exist_ok=True)
                p.rename(arch / p.name)
                done.append(f"archived {p.name}")
    return done


def selftest() -> None:
    fake = {
        "books/catalog.json": {"next_meaning": 1420, "totals": {"meanings": 420, "variants": 420, "docs": 37, "sentences": 440},
                               "books": [{"file": "books/core-m-0001.json", "kind": "meanings", "room": "core", "from": 1000, "to": 1419, "cont": []}],
                               "sections": [{"id": "encyclopedia", "title": "Encyclopedia", "store": "core", "base": "", "docs": 36, "sentences": 420,
                                             "files": ["sections/encyclopedia/docs-0001.json"], "index": ["sections/encyclopedia/index-0001.json"]},
                                            {"id": "law", "title": "Law", "store": "PxD2/cog-law", "base": "https://raw.githubusercontent.com/PxD2/cog-law/main/",
                                             "docs": 1, "sentences": 20, "files": ["sections/law/docs-0001.json"], "index": ["sections/law/index-0001.json"]}]},
        "loc/state.json": {"sources": {"q:John Knox |books": {"pages": 2, "done": False, "updated": "2026-10-11T01:00:00+00:00"}}},
        "sections/encyclopedia/index-0001.json": {"e": [{"id": "article:bill-of-rights", "k": "article", "t": "Bill of Rights", "s": "Civics & Government", "y": 1791, "sum": "Ten amendments | rights", "f": 1, "i": 0}]},
        "sections/law/index-0001.json": {"e": [{"id": "http://www.loc.gov/item/x/", "k": "doc", "t": "An Act [1791]", "y": 1791, "d": "1791", "f": 1, "i": 0, "n": 20},
                                               {"id": "https://archive.org/details/f", "k": "doc", "t": "Film", "y": 1952, "f": 1, "i": 1, "n": 4, "fm": "video", "mv": 1, "ar": "Internet Archive"}]},
    }
    files = build(lambda p: fake.get(p), now="test")
    sec = files["Sections/COG Section — Encyclopedia.md"]
    assert "[Bill of Rights](https://pxd2.github.io/cog/alexandria/#/a/bill-of-rights)" in sec and "Ten amendments \\| rights" in sec
    law = files["Sections/COG Section — Law.md"]
    assert "| Video ▶ | Internet Archive |" in law and "Text 1, Video 1" in law, law
    assert "#/src/law/1/0" in law and "An Act \\[1791\\]" in law and "raw.githubusercontent.com/PxD2/cog-law" in law
    live = files["Live/COG Library — Live.md"]
    assert "**1420**" in live and "[[COG Section — Encyclopedia]]" in live and "John Knox | search | 2 page(s) in" in live
    with tempfile.TemporaryDirectory() as d:
        assert len(write(Path(d), files)) == 3
        assert write(Path(d), files) == []                      # unchanged -> nothing rewritten
        files.pop("Sections/COG Section — Law.md")
        assert "archived COG Section — Law.md" in write(Path(d), files)       # gone upstream -> moved aside, not deleted
    print("vault sync selftest ok")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--vault", default=str(DEFAULT_VAULT))
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        selftest()
        return 0
    vault = Path(a.vault)
    if not vault.exists():
        print(f"vault not found: {vault}")
        return 2
    changed = write(vault, build())
    print(f"COG vault sync: {len(changed)} note(s) updated in {FOLDER}" + (": " + ", ".join(changed) if changed else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
